#!/usr/bin/env node
/*
 * gen-game-spotlight-posts.mjs — ゲームカタログ（assets/js/agent-data.js の GAMES）から
 * SNS投稿文を自動生成する。
 *
 * 目的: 手書きの投稿文（marketing/social_*.md）は「サイト全体」紹介に偏っていて、
 * 個別ゲームは新作リリース直後しか告知されない。GAMES は既にキュレーション済みの
 * 日英タイトル・説明文を持っているので、そこから機械的に1ゲーム1本のスポットライト
 * 投稿を作り、post-social.js の週次ローテーションへ合流させる（個別ゲームの継続告知）。
 *
 * 出力:
 *   marketing/game-spotlight-posts.generated.js  … post-social.js が require する実行用データ
 *   marketing/social_game_spotlight.md           … 人間が読む正本（verify-social-posts.mjs が検査対象にする）
 *
 * どちらも自動生成物。手編集しないこと。ゲームを追加・変更したら再生成する:
 *   node scripts/gen-game-spotlight-posts.mjs
 *
 * marketer-evolve（週次Routine）が毎回これを実行するため、ゲームカタログが変われば
 * 次回の実行で自動的に新作が投稿ローテーションへ入る。
 */
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SITE_URL = 'https://hifukasawa77-lgtm.github.io/main/';

const CATEGORY_TAG = {
  action: { ja: 'アクションゲーム', en: 'actiongame' },
  rpg:    { ja: 'RPG',             en: 'rpg' },
  board:  { ja: 'ボードゲーム',     en: 'boardgame' },
  puzzle: { ja: 'パズルゲーム',     en: 'puzzlegame' },
  sim:    { ja: 'シミュレーションゲーム', en: 'strategygame' },
  card:   { ja: 'カードゲーム',     en: 'cardgame' },
  other:  { ja: 'ブラウザゲーム',   en: 'browsergame' },
};

// GAMES 1件から X（日本語・英語）と Bluesky（日本語）のスポットライト投稿を組み立てる。
// verify-social-posts.mjs から直接呼べるよう純関数として export する（生成物の鮮度検査に使う）。
export function buildSpotlights(GAMES) {
  const x = [];
  const bluesky = [];

  for (const g of GAMES) {
    const tag = g.cat === 'other' ? null : (CATEGORY_TAG[g.cat] || null); // 'other' はベースの #ブラウザゲーム と重複するので付けない
    const url = SITE_URL + g.href;
    const extraJa = tag ? ` #${tag.ja}` : '';
    const extraEn = tag ? ` #${tag.en}` : '';

    const xJa = `${g.emoji} ${g.title.ja}\n\n${g.desc.ja}\n\nブラウザで無料・インストール不要、今すぐ遊べます。\n${url}\n\n#個人開発 #ブラウザゲーム${extraJa}`;
    const xEn = `${g.emoji} ${g.title.en}\n\n${g.desc.en}\n\nFree in your browser, no install required.\n${url}\n\n#indiedev #browsergames${extraEn}`;
    const bJa = `${g.emoji} ${g.title.ja}\n${g.desc.ja}\nブラウザで無料・インストール不要。\n${url}\n#ブラウザゲーム #個人開発${extraJa}`;

    x.push({ id: `game-${g.slug}-x-ja`, gameSlug: g.slug, text: xJa });
    x.push({ id: `game-${g.slug}-x-en`, gameSlug: g.slug, text: xEn });
    bluesky.push({ id: `game-${g.slug}-bsky-ja`, gameSlug: g.slug, text: bJa });
  }

  return { GAME_SPOTLIGHT_X: x, GAME_SPOTLIGHT_BLUESKY: bluesky };
}

function xWeightedLength(text) {
  // Xの上限は280「文字」。URLは一律23文字換算（post-social.js の本番投稿と同じ計算式）
  return text.replace(/https?:\/\/\S+/g, 'x'.repeat(23)).length;
}

function main() {
  const { GAMES } = require(path.join(ROOT, 'assets', 'js', 'agent-data.js'));
  const { GAME_SPOTLIGHT_X, GAME_SPOTLIGHT_BLUESKY } = buildSpotlights(GAMES);

  // 生成前に文字数上限を検査する（キュレーション済みの短い説明文が前提だが、
  // 将来 desc が長文化しても無言でXに弾かれないよう生成時点で止める）
  const overLimit = GAME_SPOTLIGHT_X.filter(p => xWeightedLength(p.text) > 280);
  if (overLimit.length > 0) {
    console.error('❌ X投稿の280文字上限を超えるスポットライトがあります:');
    for (const p of overLimit) console.error(`   ${p.id}: ${xWeightedLength(p.text)}/280`);
    process.exit(1);
  }

  const genPath = path.join(ROOT, 'marketing', 'game-spotlight-posts.generated.js');
  const header = `// AUTO-GENERATED by scripts/gen-game-spotlight-posts.mjs — 手編集しないこと。\n` +
    `// ゲームカタログ（assets/js/agent-data.js の GAMES）を変更したら再生成する。\n` +
    `// 生成日時: ${new Date().toISOString()}\n\n`;
  const body = `module.exports = ${JSON.stringify({ GAME_SPOTLIGHT_X, GAME_SPOTLIGHT_BLUESKY }, null, 2)};\n`;
  writeFileSync(genPath, header + body);
  console.log(`✅ ${path.relative(ROOT, genPath)} を生成（X ${GAME_SPOTLIGHT_X.length}件 / Bluesky ${GAME_SPOTLIGHT_BLUESKY.length}件、${GAMES.length}ゲーム分）`);

  const mdPath = path.join(ROOT, 'marketing', 'social_game_spotlight.md');
  const lines = [];
  lines.push('# ゲーム別スポットライト投稿（自動生成）');
  lines.push('');
  lines.push('> **このファイルは自動生成物。手編集しないこと。**');
  lines.push('> 正本は `assets/js/agent-data.js` の GAMES（タイトル・説明文）。');
  lines.push('> 再生成: `node scripts/gen-game-spotlight-posts.mjs`（ゲームカタログを変更したら必ず実行する）');
  lines.push('> 実行用の写しは `marketing/game-spotlight-posts.generated.js`。post-social.js が require して週次ローテーションへ合流させる。');
  lines.push('> 鮮度は `node scripts/verify-social-posts.mjs` の検査#8が機械確認する（GAMESと生成物がズレていたらFAIL）。');
  lines.push('');
  for (const g of GAMES) {
    const spot = GAME_SPOTLIGHT_X.filter(p => p.gameSlug === g.slug);
    const bsky = GAME_SPOTLIGHT_BLUESKY.find(p => p.gameSlug === g.slug);
    lines.push(`## ${g.title.ja} / ${g.title.en} (\`${g.slug}\`)`);
    lines.push('');
    for (const p of spot) {
      lines.push(`### ${p.id}`);
      lines.push('```');
      lines.push(p.text);
      lines.push('```');
      lines.push('');
    }
    if (bsky) {
      lines.push(`### ${bsky.id}`);
      lines.push('```');
      lines.push(bsky.text);
      lines.push('```');
      lines.push('');
    }
  }
  writeFileSync(mdPath, lines.join('\n'));
  console.log(`✅ ${path.relative(ROOT, mdPath)} を生成`);
}

// 直接実行されたときだけ生成する（verify-social-posts.mjs から import して buildSpotlights だけ使えるように）
if (import.meta.url === `file://${process.argv[1]}`) {
  main();
}
